function advancedRows() {
  const rows = D?.test_transcription?.words || [];
  const ref = D?.reference_words || [];
  const grouped = ref.map((w, i) => ({
    index: i,
    ref: w,
    reads: [],
    notes: [],
    types: [],
  }));
  rows.forEach((x) => {
    if (x.ref_index != null && grouped[x.ref_index])
      grouped[x.ref_index].reads.push(x.word || "");
    else if (x.word)
      grouped.push({
        index: null,
        ref: null,
        reads: [x.word],
        notes: [x.note || ""],
        types: [x.error_type || ""],
      });
    if (x.ref_index != null && grouped[x.ref_index]) {
      if (x.note) grouped[x.ref_index].notes.push(x.note);
      if (x.error_type && x.error_type !== "بدون خطا")
        grouped[x.ref_index].types.push(x.error_type);
    }
  });
  return grouped.map((g) => {
    const read = g.reads.join(" ").trim();
    const manualTypes = [...new Set(g.types || [])].filter(
      (x) => x && x !== "بدون خطا",
    );
    const cls = manualTypes.length
      ? manualTypeToClass(manualTypes[0], g.ref, read)
      : classifyError(g.ref, read);
    return { ...g, read, cls };
  });
}
function calculateFluencyIndex(rows) {
  const refCount = Math.max(1, D.reference_words?.length || 0);
  const errorCount = rows.filter(
    (r) => r.cls && r.cls.catKey && r.cls.catKey !== "correct",
  ).length;
  const accuracyScore = Math.max(
    0,
    Math.min(100, (1 - errorCount / refCount) * 100),
  );
  const testPauseDuration = (D.test?.pauses || []).reduce(
    (a, p) => a + Math.max(0, (p[1] || 0) - (p[0] || 0)),
    0,
  );
  const normalPauseDuration = (D.normal?.pauses || []).reduce(
    (a, p) => a + Math.max(0, (p[1] || 0) - (p[0] || 0)),
    0,
  );
  const testPauseRate =
    (D.test?.duration || 0) > 0 ? testPauseDuration / D.test.duration : 0;
  const normalPauseRate =
    (D.normal?.duration || 0) > 0 ? normalPauseDuration / D.normal.duration : 0;
  const pauseRateDelta = Math.max(0, testPauseRate - normalPauseRate);
  const pausePatternScore = Math.max(
    0,
    Math.min(100, 100 - pauseRateDelta * 500),
  );
  const pauseRatio =
    normalPauseDuration > 0
      ? testPauseDuration / normalPauseDuration
      : testPauseDuration > 0
        ? Infinity
        : 1;
  const normalWpm =
    (D.normal?.duration || 0) > 0 ? (refCount / D.normal.duration) * 60 : 0;
  const testWpm =
    (D.test?.duration || 0) > 0 ? (refCount / D.test.duration) * 60 : 0;
  let speedScore = 100;
  if (normalWpm > 0 && testWpm > 0) {
    const ratio = testWpm / normalWpm;
    speedScore = Math.max(
      0,
      Math.min(100, 100 - Math.abs(Math.log(ratio)) * 35),
    );
  }
  const index =
    accuracyScore * 0.6 + pausePatternScore * 0.2 + speedScore * 0.2;
  return {
    index,
    accuracyScore,
    pausePatternScore,
    speedScore,
    normalWpm,
    testWpm,
    testPauseDuration,
    normalPauseDuration,
    testPauseRate,
    normalPauseRate,
    pauseRateDelta,
    pauseRatio,
    errorCount,
  };
}
