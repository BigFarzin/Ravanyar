function classifyError(ref, read) {
  const r = normalizeWord(ref),
    q = normalizeWord(read);
  if (!q)
    return {
      catKey: "phonological",
      code: "E1",
      category: "خطاهای واج‌شناختی",
      type: "حذف/خراب‌خوانی واجی",
      desc: `واژه «${ref || "—"}» در خوانش ثبت‌شده حضور ندارد یا واج‌های آن به‌درستی تولید نشده‌اند.`,
      badgeClass: "badge-phon",
    };
  if (!r)
    return {
      catKey: "semantic",
      code: "E4",
      category: "خطاهای معنایی/زمینه‌ای",
      type: "خوانش افزوده/نامرتبط",
      desc: `خوانش «${read}» با واژه مرجع متناظر نیست و به‌عنوان خوانش نامرتبط/افزوده ثبت شده است.`,
      badgeClass: "badge-semantic",
    };
  if (r === q)
    return {
      catKey: "correct",
      code: "",
      category: "صحیح",
      type: "خوانش درست",
      desc: "بدون خطا و صحیح خوانده شد.",
      badgeClass: "badge-correct",
    };
  if (isDysfluent(r, q))
    return {
      catKey: "dysfluency",
      code: "E9",
      category: "ناروانی خوانش (هجا به هجا)",
      type: "خوانش تکه‌تکه / مکث‌دار",
      desc: `واژه «${ref}» به صورت تکه‌تکه یا هجا به هجا («${read}») خوانده شده است.`,
      badgeClass: "badge-dysfluency",
    };
  if (
    hasTransposition(r, q) ||
    r.split("").sort().join("") === q.split("").sort().join("")
  )
    return {
      catKey: "visual",
      code: "E2",
      category: "خطاهای دیداری-ادراکی",
      type: "وارونگی / جابه‌جایی حروف",
      desc: `توالی حروف «${ref}» در خوانش «${read}» دچار وارونگی یا جابه‌جایی شده است.`,
      badgeClass: "badge-visual",
    };
  if (isRepetition(r, q))
    return {
      catKey: "repetition",
      code: "E6",
      category: "خطای تکرار و گیر کردن",
      type: "تکرار حرف/هجا/کلمه",
      desc: `در خوانش «${read}» نسبت به «${ref}» تکرار مشاهده می‌شود.`,
      badgeClass: "badge-repetition",
    };
  const morphPatterns = [
    "ها",
    "های",
    "ان",
    "ات",
    "تر",
    "ترین",
    "ی",
    "انه",
    "وار",
    "م",
    "د",
    "یم",
    "ید",
    "ند",
    "ام",
    "ای",
    "اد",
    "ایم",
    "اید",
    "اند",
    "می",
    "نمی",
    "ب",
    "ن",
    "بر",
    "فرا",
    "وا",
  ];
  const isMorph = morphPatterns.some(
    (p) =>
      (r.endsWith(p) && !q.endsWith(p)) ||
      (!r.endsWith(p) && q.endsWith(p)) ||
      (r.startsWith(p) && !q.startsWith(p)) ||
      (!r.startsWith(p) && q.startsWith(p)),
  );
  if (
    isMorph &&
    Math.abs(r.length - q.length) <= 4 &&
    wordSimilarity(r, q) > 0.4
  )
    return {
      catKey: "morphological",
      code: "E3",
      category: "خطاهای ساخت‌واژی/نحوی",
      type: "دستکاری پسوند / شناسه",
      desc: `ساختار صرفی/پسوندی «${ref}» در خوانش «${read}» تغییر کرده است.`,
      badgeClass: "badge-morph",
    };
  if (isSynonym(r, q))
    return {
      catKey: "semantic",
      code: "E4",
      category: "خطاهای معنایی/زمینه‌ای",
      type: "حدس زدن بر اساس معنا/بافت",
      desc: `واژه «${ref}» با «${read}» جایگزین شده است و الگوی آن با حدس معنایی/زمینه‌ای سازگار است.`,
      badgeClass: "badge-semantic",
    };
  if (hasVisualSimilarity(r, q) && wordSimilarity(r, q) > 0.45)
    return {
      catKey: "memory",
      code: "E5",
      category: "خطاهای حافظه دیداری",
      type: "بازشناسی ناقص شکل واژه",
      desc: `بازشناسی شکل دقیق واژه «${ref}» در خوانش «${read}» دچار تغییر شده است.`,
      badgeClass: "badge-memory",
    };
  if (q.length > r.length + 2 && wordSimilarity(r, q) > 0.3)
    return {
      catKey: "fusion",
      code: "E7",
      category: "خطای ادغام (آمیختگی)",
      type: "ادغام دو واژه مجاور",
      desc: `خوانش «${read}» نسبت به «${ref}» طولانی‌تر است و می‌تواند ناشی از آمیختگی دو واژه مجاور باشد.`,
      badgeClass: "badge-fusion",
    };
  if (q.length < r.length - 2 && wordSimilarity(r, q) > 0.3)
    return {
      catKey: "splitting",
      code: "E8",
      category: "خطای جداسازی",
      type: "تقسیم واژه به بخش‌ها",
      desc: `واژه «${ref}» در خوانش به بخش‌های جداگانه شکسته شده است.`,
      badgeClass: "badge-splitting",
    };
  return {
    catKey: "phonological",
    code: "E1",
    category: "خطاهای واج‌شناختی",
    type: "جانشینی، تحریف یا خراب‌خوانی واج‌ها",
    desc: `خوانش «${read}» با «${ref}» متفاوت است و تغییر واجی/خراب‌خوانی محتمل است.`,
    badgeClass: "badge-phon",
  };
}

