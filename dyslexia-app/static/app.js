function playAudioSegment(a, st, en) {
  if (!a) {
    $("msg").textContent = "عنصر صوتی پیدا نشد.";
    return;
  }
  st = Number(st);
  en = Number(en);
  if (!Number.isFinite(st) || !Number.isFinite(en) || en <= st) {
    $("msg").textContent = "بازه زمانی معتبر نیست.";
    return;
  }
  if (!a.src) {
    $("msg").textContent = "فایل صوتی هنوز بارگذاری نشده است.";
    return;
  }
  if (a._segmentTimer) {
    clearInterval(a._segmentTimer);
    a._segmentTimer = null;
  }
  try {
    a.pause();
  } catch (e) {}
  const startPlayback = () => {
    try {
      const maxT =
        Number.isFinite(a.duration) && a.duration > 0 ? a.duration : en;
      a.currentTime = Math.max(0, Math.min(st, Math.max(0, maxT - 0.01)));
      const p = a.play();
      if (p && p.catch)
        p.catch((err) => {
          $("msg").textContent =
            "مرورگر اجازه پخش فایل صوتی را نداد: " +
            (err?.message || "Playback failed");
        });
      a._segmentTimer = setInterval(() => {
        if (
          !a.paused &&
          Number.isFinite(a.currentTime) &&
          a.currentTime >= en - 0.02
        ) {
          clearInterval(a._segmentTimer);
          a._segmentTimer = null;
          try {
            a.pause();
          } catch (e) {}
        }
      }, 25);
    } catch (e) {
      $("msg").textContent = "پخش قطعه صوتی انجام نشد: " + e.message;
    }
  };
  if (a.readyState >= 1 && Number.isFinite(a.duration)) {
    startPlayback();
    return;
  }
  const once = () => {
    a.removeEventListener("loadedmetadata", once);
    startPlayback();
  };
  a.addEventListener("loadedmetadata", once, { once: true });
  try {
    a.load();
  } catch (e) {}
}
