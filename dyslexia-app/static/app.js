function autoMapTestWordsToReference() {
  const rows = D.test_transcription?.words || [],
    ref = D.reference_words || [];
  const manual = rows.map(
    (x) => x.mapping_manual === true && x.ref_index != null,
  );
  rows.forEach((x, i) => {
    if (!manual[i]) x.ref_index = null;
  });
  const n = ref.length,
    m = rows.length;
  if (!n || !m) return;
  // Preserve explicit user mappings. Automatically align only the remaining rows.
  const freeRows = rows
    .map((x, i) => (manual[i] ? null : i))
    .filter((x) => x != null);
  const freeRefs = ref
    .map((_, i) => i)
    .filter((i) => !rows.some((x, j) => manual[j] && x.ref_index === i));
  if (!freeRows.length || !freeRefs.length) {
    rows.forEach((x) => {
      if (x.ref_index != null) {
        const cls = classifyError(ref[x.ref_index], x.word || "");
        if (!x.error_manual && (!x.error_type || x.error_type === "بدون خطا"))
          x.error_type = cls.catKey === "correct" ? "بدون خطا" : cls.type;
      }
    });
    return;
  }
  const rr = freeRefs.length,
    mm = freeRows.length;
  const dp = Array.from({ length: rr + 1 }, () =>
    Array(mm + 1).fill(-Infinity),
  );
  const back = Array.from({ length: rr + 1 }, () => Array(mm + 1).fill(null));
  dp[0][0] = 0;
  for (let i = 0; i <= rr; i++)
    for (let j = 0; j <= mm; j++) {
      if (i < rr && dp[i][j] > -Infinity) {
        if (dp[i][j] - 1.15 > dp[i + 1][j]) {
          dp[i + 1][j] = dp[i][j] - 1.15;
          back[i + 1][j] = { pi: i, pj: j, type: "omit" };
        }
        for (let k = 1; k <= Math.min(4, mm - j); k++) {
          const parts = freeRows
            .slice(j, j + k)
            .map((ix) => normalizeWord(rows[ix].word || ""));
          const joined = parts.join(""),
            spaced = parts.join(" "),
            sim = Math.max(
              wordSimilarity(ref[freeRefs[i]], joined),
              wordSimilarity(ref[freeRefs[i]], spaced),
            );
          if (sim < 0.25) continue;
          const score = dp[i][j] + sim * 3 - 0.25 - 0.18 * (k - 1);
          if (score > dp[i + 1][j + k]) {
            dp[i + 1][j + k] = score;
            back[i + 1][j + k] = { pi: i, pj: j, type: "match", k };
          }
        }
      }
      if (j < mm && dp[i][j] > -Infinity && dp[i][j] - 0.85 > dp[i][j + 1]) {
        dp[i][j + 1] = dp[i][j] - 0.85;
        back[i][j + 1] = { pi: i, pj: j, type: "add" };
      }
    }
  let i = rr,
    j = mm,
    groups = [];
  while (i > 0 || j > 0) {
    const b = back[i][j];
    if (!b) break;
    if (b.type === "match") {
      groups.unshift({ ref: freeRefs[i - 1], start: b.pj, end: j });
      i = b.pi;
      j = b.pj;
    } else if (b.type === "omit") {
      i = b.pi;
      j = b.pj;
    } else {
      j = b.pj;
      i = b.pi;
    }
  }
  groups.forEach((g) => {
    for (let k = g.start; k < g.end; k++) {
      const row = rows[freeRows[k]];
      row.ref_index = g.ref;
      const cls = classifyError(ref[g.ref], row.word || "");
      if (
        !row.error_manual &&
        (!row.error_type || row.error_type === "بدون خطا")
      )
        row.error_type = cls.catKey === "correct" ? "بدون خطا" : cls.type;
    }
  });
  rows.forEach((row, idx) => {
    if (row.ref_index != null) {
      const cls = classifyError(ref[row.ref_index], row.word || "");
      if (
        !row.error_manual &&
        (!row.error_type || row.error_type === "بدون خطا")
      )
        row.error_type = cls.catKey === "correct" ? "بدون خطا" : cls.type;
    }
  });
}
function rebuildReferenceTestTiming() {
  const ref = D.reference_words || [],
    rows = D.test_transcription?.words || [];
  D.test.words = ref.map((w, i) => ({
    index: i,
    word: w,
    start: null,
    end: null,
    confirmed: true,
    error_type: "بدون خطا",
  }));
  ref.forEach((w, i) => {
    const group = rows
      .filter((x) => x.ref_index === i && x.start != null && x.end != null)
      .sort((a, b) => a.start - b.start);
    if (group.length) {
      D.test.words[i].start = Math.min(...group.map((x) => Number(x.start)));
      D.test.words[i].end = Math.max(...group.map((x) => Number(x.end)));
    }
    const errs = [
      ...new Set(
        rows
          .filter(
            (x) =>
              x.ref_index === i && x.error_type && x.error_type !== "بدون خطا",
          )
          .map((x) => x.error_type),
      ),
    ];
    if (errs.length) D.test.words[i].error_type = errs.join("؛ ");
  });
}

function compareReferenceWithTest() {
  const rows = (D.test_transcription?.words || []).slice();
  const groups = D.reference_words.map((w, i) => ({
    index: i,
    reference: w,
    test: [],
    error_types: [],
  }));
  rows.forEach((x) => {
    if (x.ref_index != null && groups[x.ref_index])
      groups[x.ref_index].test.push(x);
  });
  const out = [];
  groups.forEach((g) => {
    const parts = g.test
      .slice()
      .sort((a, b) => (Number(a.start) || 0) - (Number(b.start) || 0));
    const read = parts
      .map((x) => x.word || "")
      .filter(Boolean)
      .join(" ")
      .trim();
    const errs = [];
    parts.forEach((x) => {
      const auto = classifyError(g.reference, x.word || "");
      if (x.error_type && x.error_type !== "بدون خطا") errs.push(x.error_type);
      else if (auto.catKey !== "correct") errs.push(auto.type);
    });
    let status = "درست";
    if (!parts.length) status = "حذف/خوانده‌نشده";
    else if (read !== g.reference) status = "اختلاف خوانش";
    if (errs.length) status = status === "درست" ? "خطای ثبت‌شده" : status;
    out.push({
      index: g.index,
      reference: g.reference,
      test: read || "—",
      status,
      error_type: [...new Set(errs)].join("؛ "),
    });
  });
  rows
    .filter((x) => x.ref_index == null)
    .forEach((x) =>
      out.push({
        index: null,
        reference: "—",
        test: x.word || "—",
        status: "افزوده/بدون تطبیق",
        error_type: x.error_type === "بدون خطا" ? "" : x.error_type,
      }),
    );
  return out;
}
