function isDysfluent(ref, read) {
  if (!ref || !read || ref === read) return false;
  // معیار ۱: کلمه خوانده شده دارای فاصله‌های زیاد (بیش از ۲ کاراکتر فاصله) بین حروف است
  // معیار ۲: طول کلمه خوانده شده حداقل ۲ کاراکتر بیشتر از کلمه مرجع است (بدون احتساب خطاهای ادغام)
  // معیار ۳: وجود حروف تکراری یا کشیدگی غیرمعمول (مانند "خو ا ب" برای "خواب")

  // حذف فاصله‌ها و کاراکترهای خاص برای بررسی دقیق‌تر
  const readClean = read.replace(/[_\s\u200c]/g, "");
  const refClean = ref.replace(/[_\s\u200c]/g, "");

  // اگر تفاوت طول زیاد باشد (بیش از ۳ کاراکتر) و شباهت کم باشد، احتمال ناروانی بالا است
  const lenDiff = readClean.length - refClean.length;
  const sim = wordSimilarity(refClean, readClean);

  // بررسی کشیدگی حروف (تکرار یک حرف در کلمه خوانده شده)
  let hasElongation = false;
  for (let i = 1; i < readClean.length; i++) {
    if (readClean[i] === readClean[i - 1] && readClean[i] !== " ") {
      hasElongation = true;
      break;
    }
  }

  // بررسی وجود فاصله در کلمه خوانده شده (نشانه جداسازی هجاها)
  const hasSpacing =
    read.includes(" ") || read.includes("_") || read.includes("\u200c");

  // معیار ناروانی: اگر تفاوت طول زیاد باشد یا کشیدگی وجود داشته باشد یا فاصله‌گذاری غیرعادی باشد
  if (
    (lenDiff >= 2 && sim < 0.7) ||
    hasElongation ||
    (hasSpacing && read.length > ref.length + 1)
  ) {
    return true;
  }

  return false;
}

